{#-
  Per-student table naming.

  Every model dbt builds gets YOUR prefix appended (e.g. DIM_NEWS_SMITHJ) so your
  tables don't overwrite a classmate's in the shared STAGING / MODELED schemas.

  You do NOT edit this file. Set your prefix once in dbt_project.yml:

      vars:
        student_prefix: "SMITHJ"   # <- your last-name + first-initial

  dbt calls this macro automatically for every model to decide its final table/view
  name, so staging views, warehouse tables, and mart tables all get tagged in one shot.
  If you forget to set your prefix, dbt stops with a clear error instead of silently
  overwriting someone else's tables.
-#}
{% macro generate_alias_name(custom_alias_name=none, node=none) -%}

    {%- set base  = custom_alias_name if custom_alias_name is not none else node.name -%}
    {%- set token = var('student_prefix', env_var('DBT_STUDENT', '')) | trim -%}

    {%- if token in ('', 'SMITHJ') -%}
        {{ exceptions.raise_compiler_error(
            "Set vars.student_prefix in dbt_project.yml to YOUR prefix (not the SMITHJ example) before running dbt.") }}
    {%- endif -%}

    {{ base ~ '_' ~ token }}

{%- endmacro %}
